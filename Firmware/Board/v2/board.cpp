void start_timers() {
    CRITICAL_SECTION() {
        // Temporarily disable ADC triggers so they don't trigger as a side
        // effect of starting the timers.
        hadc1.Instance->JSQR &= ~ADC_JSQR_JEXTEN;
        hadc2.Instance->CFGR &= ~ADC_CFGR_EXTEN;
        hadc2.Instance->JSQR &= ~ADC_JSQR_JEXTEN;
        hadc3.Instance->CFGR &= ~ADC_CFGR_EXTEN;
        hadc3.Instance->JSQR &= ~ADC_JSQR_JEXTEN;

        /*
        * Synchronize TIM1, TIM8 and TIM13 such that:
        *  1. The triangle waveform of TIM1 leads the triangle waveform of TIM8 by a
        *     90° phase shift.
        *  2. Each TIM13 reload coincides with a TIM1 lower update event.
        */
        Stm32Timer::start_synchronously<3>(
            {&htim1, &htim8, &htim16},
            {TIM1_INIT_COUNT, 0, TIM1_INIT_COUNT /* TIM16 is on a clock as fast as TIM1 */}
        );

        hadc1.Instance->JSQR |= ADC_EXTERNALTRIGINJECCONV_EDGE_RISING;
        hadc2.Instance->CFGR |= ADC_EXTERNALTRIGCONVEDGE_RISING;
        hadc2.Instance->JSQR |= ADC_EXTERNALTRIGINJECCONV_EDGE_RISING;
        hadc3.Instance->CFGR |= ADC_EXTERNALTRIGCONVEDGE_RISING;
        hadc3.Instance->JSQR |= ADC_EXTERNALTRIGINJECCONV_EDGE_RISING;

        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_OVR);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_OVR);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_OVR);
        
        __HAL_TIM_CLEAR_IT(&htim8, TIM_IT_UPDATE);
        __HAL_TIM_ENABLE_IT(&htim8, TIM_IT_UPDATE);
    }
}

void infra_sense_adc_cb(uint32_t adc_value) {
    infra_adc_raw = (uint16_t)(adc_value & 0xFFFU);
}

void infra_pwm_init() {
    // CubeMX 已完成: RCC 时钟、GPIO 输出、TIM15 时基+CC1E、NVIC 优先级 15
    // 这里补上: CCR1 预加载、UEV+CC1 中断使能、启动
    TIM15->CCMR1 |= TIM_CCMR1_OC1PE;
    TIM15->CCR1 = 0;
    TIM15->EGR = TIM_EGR_UG;
    TIM15->DIER |= TIM_DIER_UIE | TIM_DIER_CC1IE;
    __HAL_TIM_CLEAR_FLAG(&htim15, TIM_FLAG_UPDATE | TIM_FLAG_CC1);
    __HAL_TIM_ENABLE(&htim15);
}

static bool fetch_and_reset_adcs(
        std::optional<Iph_ABC_t>* current0,
        std::optional<Iph_ABC_t>* current1) {
    bool all_adcs_done = (ADC1->ISR & (ADC_ISR_EOC | ADC_ISR_JEOC)) == (ADC_ISR_EOC | ADC_ISR_JEOC)
        && (ADC2->ISR & (ADC_ISR_EOC | ADC_ISR_JEOC)) == (ADC_ISR_EOC | ADC_ISR_JEOC)
        && (ADC3->ISR & (ADC_ISR_EOC | ADC_ISR_JEOC)) == (ADC_ISR_EOC | ADC_ISR_JEOC);
    if (!all_adcs_done) {
        return false;
    }

    vbus_sense_adc_cb(ADC1->JDR1);
    infra_sense_adc_cb(ADC1->DR);

    // 红外 LED 阈值控制：无球灯灭，有球随电压增大越来越亮
    // 1V = 1241 ADC (3.3V ref, 12-bit)，迟滞 50 LSB 防抖
    static bool infra_pwm_active = false;
    static const uint16_t INFRA_THRESHOLD_ON  = 1241;   // ~1.0V
    static const uint16_t INFRA_THRESHOLD_OFF = 1191;   // ~0.96V
    static const uint16_t INFRA_MAX_ADC = 4095;
    static const uint16_t INFRA_MAX_DUTY = 4085;

    // 迟滞状态机
    bool prev_active = infra_pwm_active;
    if (!infra_pwm_active && infra_adc_raw >= INFRA_THRESHOLD_ON) {
        infra_pwm_active = true;
    } else if (infra_pwm_active && infra_adc_raw <= INFRA_THRESHOLD_OFF) {
        infra_pwm_active = false;
    }

    // 只在状态切换时动 TIM15 配置，避免每轮清除更新标志导致丢失 PWM 周期
    if (infra_pwm_active && !prev_active) {
        // off→on：恢复更新中断，清除可能挂起的旧标志（一次性）
        __HAL_TIM_CLEAR_FLAG(&htim15, TIM_FLAG_UPDATE);
        TIM15->DIER |= TIM_DIER_UIE;
    } else if (!infra_pwm_active && prev_active) {
        // on→off：禁止更新中断，强制拉低
        TIM15->DIER &= ~TIM_DIER_UIE;
    }

    if (infra_pwm_active) {
        // CCR1 有预加载，写入安全，下个更新事件生效
        uint32_t duty = ((uint32_t)(infra_adc_raw - INFRA_THRESHOLD_ON) * INFRA_MAX_DUTY)
                      / (INFRA_MAX_ADC - INFRA_THRESHOLD_ON);
        TIM15->CCR1 = (duty >= INFRA_MAX_DUTY) ? 4086u : (uint16_t)duty;
    } else {
        // 无球：引脚强制拉低，确保彻底灭
        HAL_GPIO_WritePin(GPIOC, GPIO_PIN_14, GPIO_PIN_RESET);
    }

    std::optional<float> phA = motors[0].phase_current_from_adcval(ADC2->JDR1);
    std::optional<float> phB = motors[0].phase_current_from_adcval(ADC3->JDR1);
    if (phA.has_value() && phB.has_value()) {
        *current0 = {*phA, *phB, -*phA - *phB};
    }

    phA = motors[1].phase_current_from_adcval(ADC2->DR);
    phB = motors[1].phase_current_from_adcval(ADC3->DR);
    if (phA.has_value() && phB.has_value()) {
        *current1 = {*phA, *phB, -*phA - *phB};
    }
    
    ADC1->ISR = ~(ADC_ISR_EOC | ADC_ISR_JEOC | ADC_ISR_OVR);
    ADC2->ISR = ~(ADC_ISR_EOC | ADC_ISR_JEOC | ADC_ISR_OVR);
    ADC3->ISR = ~(ADC_ISR_EOC | ADC_ISR_JEOC | ADC_ISR_OVR);

    return true;
}

